import "./env.js"; // must run before anything reads process.env
import { generateTest } from "./generate.js";

const description = process.argv.slice(2).join(" ").trim();

if (!description) {
  console.error(`Usage: npm run gen -- "<what to test>"

Examples:
  npm run gen -- "log in as the standard user and check the products page appears"
  npm run gen -- "log in as a locked out user and check the error message"

Then run it:  npm test`);
  process.exit(1);
}

const baseURL = process.env.BASE_URL ?? "https://www.saucedemo.com";

try {
  const result = await generateTest({ description, baseURL });

  const origin =
    result.source === "claude"
      ? `generated by Claude — ${result.usage!.inputTokens} in / ${result.usage!.outputTokens} out, ~$${result.usage!.estimatedCostUsd.toFixed(4)}`
      : "replayed from cache (no API call)";

  console.log(`\n✓ ${result.outputPath}`);
  console.log(`  ${origin}`);
  console.log(`\nRun it with:  npm test -- ${result.filename}\n`);
} catch (error) {
  console.error(`\n✗ ${error instanceof Error ? error.message : String(error)}\n`);
  process.exit(1);
}
